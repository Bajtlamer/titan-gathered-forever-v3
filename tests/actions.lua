local ns={}
assert(loadfile('TitanGatheredForeverV3/Actions.lua'))('TGF v3',ns)
local passed=0
local function eq(a,b)assert(a==b,tostring(a)..' != '..tostring(b))end
local function test(n,f)local ok,e=pcall(f);if not ok then error(n..': '..e)end;passed=passed+1 end
local function fixture(saved)
 local s={character='a',clock=100,enabled=true,changes=0}
 local a=ns.Actions.New(saved or {},{Character=function()return s.character end,Name=function()return s.character end,
  Timestamp=function()return s.clock end,Now=function()return s.clock end,Enabled=function()return s.enabled end,
  Changed=function()s.changes=s.changes+1 end})
 return a,s
end
local function cast(a,event,guid,spell,unit)a:Cast('UNIT_SPELLCAST_'..event,unit or 'player',guid or 'one',spell or 2575)end
test('duplicates and stop before success count one completed attempt',function()
 local a=fixture();cast(a,'START');cast(a,'START');cast(a,'STOP');cast(a,'SUCCEEDED');cast(a,'SUCCEEDED');cast(a,'STOP')
 local r=a:Rows('a')[1];eq(r.attempts,1);eq(r.completed,1);eq(r.stopped,0);eq(r.unresolved,0);eq(r.began,100)
end)
test('all five professions have independent evidenced action counters',function()
 local a=fixture()
 for i,id in ipairs({2575,2366,8613,13262,7620})do cast(a,'SUCCEEDED','c'..i,id)end
 local rows=a:Rows('a');eq(#rows,5)
 for _,r in ipairs(rows)do eq(r.attempts,1);eq(r.completed,r.kind=='Fishing'and 0 or 1)end
end)
test('failures and interruptions remain separate without duplicate attempts',function()
 local a=fixture();cast(a,'START','a');cast(a,'FAILED','a');cast(a,'FAILED','a');cast(a,'STOP','a')
 cast(a,'START','b');cast(a,'INTERRUPTED','b');cast(a,'STOP','b')
 local r=a:Rows()[1];eq(r.attempts,2);eq(r.failed,1);eq(r.interrupted,1);eq(r.completed,0);eq(r.stopped,0)
end)
test('fishing launch is not catch and late fishing loot supersedes stop',function()
 local a=fixture();cast(a,'SUCCEEDED','fish',7620);cast(a,'CHANNEL_START','fish',7620)
 eq(a:Rows()[1].completed,0);cast(a,'CHANNEL_STOP','fish',7620);a:FishingLoot();a:FishingLoot()
 local r=a:Rows()[1];eq(r.attempts,1);eq(r.completed,1);eq(r.stopped,0)
end)
test('fishing catch can follow an interruption without double counting',function()
 local a=fixture();cast(a,'CHANNEL_START','fish',7620);cast(a,'INTERRUPTED','fish',7620);a:FishingLoot()
 eq(a:Rows()[1].completed,1);eq(a:Rows()[1].interrupted,0)
end)
test('unconfirmed stops are not failures or completions',function()
 local a=fixture();cast(a,'STOP');eq(#a:Rows(),0);cast(a,'START');cast(a,'STOP')
 local r=a:Rows()[1];eq(r.stopped,1);eq(r.failed,0);eq(r.completed,0)
end)
test('stale or superseded fishing context cannot claim later loot',function()
 local a,s=fixture();cast(a,'CHANNEL_START','fish',7620);s.clock=146;a:FishingLoot();eq(a:Rows()[1].completed,0)
 cast(a,'CHANNEL_START','next',7620);cast(a,'START','other',123);a:FishingLoot();eq(a:Rows()[1].completed,0)
end)
test('invalid events and nonplayer spells do not record attempts',function()
 local a=fixture();cast(a,'START','x',2575,'party1');cast(a,'START','x',123);cast(a,'START',42);cast(a,'START','',2575)
 cast(a,'SENT');eq(#a:Rows(),0)
end)
test('paused recording seals pending action without guessing an outcome',function()
 local a,s=fixture();cast(a,'START');a:Pause();s.enabled=false;cast(a,'SUCCEEDED');s.enabled=true;cast(a,'SUCCEEDED')
 local r=a:Rows()[1];eq(r.attempts,1);eq(r.completed,0);eq(r.unresolved,1)
 cast(a,'START','two');cast(a,'SUCCEEDED','two');eq(a:Rows()[1].completed,1)
end)
test('reload preserves totals and prevents late results from filling old gaps',function()
 local saved={};local a=fixture(saved);cast(a,'START');local b=fixture(saved);cast(b,'SUCCEEDED')
 local r=b:Rows()[1];eq(r.attempts,1);eq(r.unresolved,1);eq(r.completed,0);eq(saved.schema,1)
end)
test('combined view sums counts and retains earliest coverage start',function()
 local a,s=fixture();cast(a,'SUCCEEDED');s.character='b';s.clock=200;cast(a,'START','two');cast(a,'FAILED','two')
 local r=a:Rows()[1];eq(r.attempts,2);eq(r.completed,1);eq(r.failed,1);eq(r.began,100)
 eq(a:Rows('b')[1].began,200);eq(a:Rows('a')[1].attempts,1)
end)
test('recent receipts are bounded while lifetime totals remain intact',function()
 local saved={};local a=fixture(saved)
 for i=1,1100 do cast(a,'SUCCEEDED','c'..i)end
 eq(a:Rows()[1].attempts,1100);eq(a:Rows()[1].completed,1100);eq(#saved.characters.a.order,1024)
 local n=0;for _ in pairs(saved.characters.a.recent)do n=n+1 end;eq(n,1024)
end)
test('late fishing events cannot revive a superseded catch context',function()
 local a=fixture();cast(a,'CHANNEL_START','old',7620);cast(a,'START','other',123)
 cast(a,'SUCCEEDED','old',7620);a:FishingLoot();eq(a:Rows()[1].completed,0)
 cast(a,'CHANNEL_START','new',7620);cast(a,'CHANNEL_STOP','old',7620)
 cast(a,'SUCCEEDED','old',7620);cast(a,'CHANNEL_START','old',7620);a:FishingLoot();eq(a:Rows()[1].completed,1)
 eq(a.saved.characters.a.recent.new.outcome,'completed');eq(a.saved.characters.a.recent.old.outcome,'stopped')
end)
test('future schemas remain untouched and refuse recording',function()
 local saved={schema=2,characters={future=true}};local a=fixture(saved)
 cast(a,'START');a:Pause();eq(#a:Rows(),0);eq(saved.characters.future,true)
end)
