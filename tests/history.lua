 local saved={};local h=ns.History.New(saved)
 h:Observe('a','A',event('one',{[2770]=2}))
 h:Observe('b','B',event('one',{[2770]=4}))
 h:Observe('b','B',event('two',{[2770]=1}))
 saved.characters.a.items[2770].acquisitions=nil
 saved.characters.a.items[2770].acquisitionsIncomplete=nil
 h=ns.History.New(saved)
 local a,b,all=h:Totals('a')[1],h:Totals('b')[1],h:Totals(nil)[1]
 eq(a.acquisitions,1);eq(a.acquisitionsIncomplete,true)
 eq(b.acquisitions,2);eq(b.acquisitionsIncomplete,false)
 eq(all.acquisitions,3);eq(all.quantity,7);eq(all.acquisitionsIncomplete,true)
end)
