def lua(value):
    """A Lua literal for a Python value, written the way the game writes saved variables."""
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
    if isinstance(value, dict):
        parts = []
        for key, inner in value.items():
            parts.append(f'[{lua(key)}] = {lua(inner)},')
        return '{\n' + '\n'.join(parts) + '\n}'
    raise TypeError(value)


EMPTY = {c: {} for c in ('loot', 'npcs', 'vendors', 'entities', 'quests', 'areas', 'skills', 'recipes', 'maps')}


def database(data=None, **extra):
    merged = {c: dict(v) for c, v in EMPTY.items()}
    for category, records in (data or {}).items():
        merged[category].update(records)
    db = {'meta': {'schemaVersion': 1, 'moduleVersion': '0.1.0', 'createdAt': 100,
                   'client': {'version': '1.60.1', 'build': '70862', 'interface': 16001, 'locale': 'enUS'},
                   'builds': {'70862': 100}},
          'consent': {'accepted': True, 'paused': False, 'version': 2, 'acceptedAt': 100},
          'data': merged, 'reviewed': {}, 'archives': {}}
    db.update(extra)
    return db


def sv(db, name='TitanGatheredForeverDiscoveryDB'):
    return f'{name} = {lua(db)}\n'


def rec(seen=1, first=100, last=200, build='70862', **fields):
    record = {'seen': seen, 'first': first, 'last': last, 'firstBuild': build, 'lastBuild': build}
    record.update(fields)
    return record


