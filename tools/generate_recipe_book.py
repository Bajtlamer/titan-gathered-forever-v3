#!/usr/bin/env python3
"""Generate TitanGatheredForeverV3/Data/RecipeBook.lua from catalogue/forever-recipes.json.

The runtime catalogue keeps only the reagents of the recipes. The recipe book keeps, for every recipe of the pinned
Forever table, the product and the materials, so the profit of a craft can be worked out for recipes the player
has not opened. The table is a mirror of client tables and is not complete; the live schematic of the client wins
wherever it is available.

Usage: generate_recipe_book.py          write the file
       generate_recipe_book.py --check  fail when the file is stale
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'catalogue/forever-recipes.json'
OUTPUT = ROOT / 'TitanGatheredForeverV3/Data/RecipeBook.lua'


def render():
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    recipes = data['recipes']
    professions = sorted({recipe['profession'] for recipe in recipes})
    index = {name: number for number, name in enumerate(professions, start=1)}
    lines = [
        '-- Generated by tools/generate_recipe_book.py. Do not edit.',
        '-- Source: catalogue/forever-recipes.json (%s, client %s, build %s, retrieved %s).' % (
            data['source'], data['clientVersion'], data['targetBuild'], data['retrieved']),
        '-- Mirror of client tables, not complete (complete = %s). Each recipe: [spellID] = { product, profession, { { item, quantity }, ... } }.'
        % str(bool(data.get('complete'))).lower(),
        'local _, ns = ...',
        'ns.RecipeBook = {',
        '    complete = %s,' % str(bool(data.get('complete'))).lower(),
        '    professions = { %s },' % ', '.join('"%s"' % name for name in professions),
        '    recipes = {',
    ]
    for recipe in sorted(recipes, key=lambda item: item['spellID']):
        reagents = ','.join('{%d,%d}' % (reagent['itemID'], reagent['quantity']) for reagent in recipe['reagents'])
        lines.append('        [%d]={%d,%d,{%s}},' % (recipe['spellID'], recipe['outputItemID'], index[recipe['profession']], reagents))
    lines += ['    },', '}', '']
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != text:
            print('RecipeBook.lua is stale; run tools/generate_recipe_book.py', file=sys.stderr)
            return 1
        print('RecipeBook.lua is current')
        return 0
    OUTPUT.write_text(text, encoding='utf-8')
    print('wrote %s (%d bytes)' % (OUTPUT.relative_to(ROOT), len(text.encode('utf-8'))))
    return 0


if __name__ == '__main__':
    sys.exit(main())
